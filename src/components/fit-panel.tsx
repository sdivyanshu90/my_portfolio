"use client";

import { useMemo, useState } from "react";
import { personal, resume, site } from "@/data/portfolio";
import {
  type FitRow,
  fitSummary,
  interviewQuestions,
  matchRequirements,
  parseRequirements,
  STRENGTH_LABELS,
} from "@/lib/fit";
import { beacon } from "@/lib/beacon";

/**
 * Paste a job description → requirement-by-requirement evidence from the
 * dossier, with honest gaps. Runs entirely in the browser: the JD is never
 * sent anywhere (only the summary counts are logged). The result
 * exports as a one-page brief a recruiter can forward.
 */

const BADGE: Record<FitRow["strength"], string> = {
  strong: "bg-accent text-paper",
  partial: "border border-accent text-accent",
  verify: "border border-rule text-ink-muted",
  gap: "border border-rule text-ink-faint",
};

const SAMPLE = `Senior ML Engineer — LLM Platform
- Production ML systems in Python
- PyTorch and Hugging Face Transformers
- LLM inference serving: batching, KV cache, quantization
- Retrieval-augmented generation and vector databases
- LLM evaluation and guardrails against prompt injection
- Kubernetes for infrastructure`;

const titleOf = (jd: string) =>
  jd
    .split("\n")
    .map((l) => l.trim())
    .find(Boolean)
    ?.slice(0, 80) ?? "the role";

/** A prefilled email to Divanshu: the recruiter sends it from their own client. */
function replyHref(rows: FitRow[], jd: string): string {
  const s = fitSummary(rows);
  const list = (k: FitRow["strength"]) =>
    rows
      .filter((r) => r.strength === k)
      .map((r) => `- ${r.requirement}`)
      .join("\n")
      .slice(0, 600);
  const body = [
    "Hi Divanshu,",
    "",
    `I ran the fit check on your portfolio against our role (${titleOf(jd)}): ${s.strong} supported, ${s.partial} partial, ${s.verify} to verify, ${s.gap} without evidence.`,
    "",
    `Supported:\n${list("strong") || "-"}`,
    "",
    s.verify ? `To verify:\n${list("verify")}` : "",
    s.gap ? `Evidence gaps we'd want to discuss:\n${list("gap")}` : "",
    "",
    "Would you be open to a conversation?",
    "",
  ].join("\n");
  return `mailto:${personal.email}?subject=${encodeURIComponent(`Role: ${titleOf(jd)}`)}&body=${encodeURIComponent(body)}`;
}

function brief(rows: FitRow[], jd: string): string {
  const s = fitSummary(rows);
  const title = titleOf(jd);
  const questions = interviewQuestions(rows);
  const lines = [
    `# ${personal.name} — fit against “${title}”`,
    "",
    `${personal.lead} · ${personal.currentRole} · ${personal.openTo}.`,
    "",
    `**${s.strong} supported · ${s.partial} partial · ${s.verify} to verify · ${s.gap} without evidence** across ${s.total} requirements. Local evidence checks, not a hiring prediction. Unrecognized wording may need manual review.`,
    "",
    "| Requirement | Priority | Match | Reason | Evidence |",
    "|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.requirement.replace(/\|/g, "/")} | ${r.priority} | ${STRENGTH_LABELS[r.strength]} | ${r.explanation.replace(/\|/g, "/")} | ${
          r.evidence
            .map((e) => `[${e.name}](${e.url}) (${e.scope})`)
            .join(", ") || "—"
        } |`,
    ),
    "",
    ...(questions.length
      ? [
          "## Suggested deep-dive questions",
          "",
          ...questions.map((q) => `- ${q.q} (read first: ${q.url})`),
          "",
        ]
      : []),
    `Contact: ${personal.email} · CV: ${site.url}/cv · Résumé: ${resume.href}`,
    `Generated by DIV-1 (${site.url}) on ${new Date().toISOString().slice(0, 10)}.`,
  ];
  return lines.join("\n");
}

export function FitPanel({ initial = "" }: { initial?: string }) {
  const [jd, setJd] = useState(initial);
  const [ran, setRan] = useState(initial ? initial : "");
  const [copied, setCopied] = useState(false);
  const rows = useMemo(() => (ran ? matchRequirements(ran) : []), [ran]);
  const s = fitSummary(rows);
  const stale = !!ran && jd !== ran;
  const parsed = useMemo(() => parseRequirements(ran), [ran]);
  const questions = useMemo(() => interviewQuestions(rows), [rows]);

  const run = () => {
    setRan(jd);
    const r = matchRequirements(jd);
    const c = fitSummary(r);
    beacon("fit", {
      requirements: c.total,
      strong: c.strong,
      partial: c.partial,
      verify: c.verify,
      gap: c.gap,
    });
  };

  const exportMd = (mode: "copy" | "download") => {
    const md = brief(rows, ran);
    beacon("brief", { mode, requirements: rows.length });
    if (mode === "copy") {
      navigator.clipboard?.writeText(md).then(() => {
        setCopied(true);
        setTimeout(() => setCopied(false), 1800);
      });
    } else {
      const a = document.createElement("a");
      a.href = URL.createObjectURL(new Blob([md], { type: "text/markdown" }));
      a.download = `divanshu-sharma-fit-${new Date().toISOString().slice(0, 10)}.md`;
      a.click();
      URL.revokeObjectURL(a.href);
    }
  };

  return (
    <div>
      <label
        htmlFor="fit-jd"
        className="font-mono text-[11px] tracking-[0.15em] text-ink-faint uppercase"
      >
        Job description or requirements
      </label>
      <textarea
        id="fit-jd"
        value={jd}
        onChange={(e) => setJd(e.target.value)}
        rows={7}
        maxLength={20000}
        placeholder={
          "Paste the JD — one requirement per line works best.\n\nYour text stays in this browser."
        }
        className="mt-2 w-full resize-y border border-rule bg-surface px-3 py-2.5 font-mono text-[12px] leading-relaxed text-ink placeholder:text-ink-faint focus:border-accent focus:outline-none"
      />
      <div className="mt-2 flex flex-wrap items-center gap-3">
        <button
          type="button"
          onClick={run}
          disabled={!jd.trim()}
          className="border border-accent px-4 py-1.5 font-mono text-[11px] tracking-wider text-accent uppercase transition-colors hover:bg-accent hover:text-paper disabled:opacity-40"
        >
          match
        </button>
        {!jd ? (
          <button
            type="button"
            onClick={() => setJd(SAMPLE)}
            className="font-mono text-[11px] text-ink-faint underline underline-offset-2 hover:text-accent"
          >
            try a sample JD
          </button>
        ) : null}
        <span className="font-mono text-[11px] text-ink-faint">
          matched in your browser · never sent · no model
        </span>
      </div>

      {stale ? (
        <p className="mt-3 text-sm text-accent" role="status">
          The description has changed. Run match again before sharing these
          results.
        </p>
      ) : null}
      {rows.length ? (
        <div className="mt-6">
          <p className="font-mono text-[12px] text-ink" aria-live="polite">
            <span className="text-accent">{s.strong} supported</span> ·{" "}
            {s.partial} partial · {s.verify} to verify · {s.gap} without
            evidence — {s.total} requirements
          </p>
          <p className="mt-2 text-[12px] leading-relaxed text-ink-muted">
            Supported means the recognized skills have evidence. Verify covers
            unresolved years, scope or eligibility. No evidence means absent
            from this portfolio, not proof of inability. Review each
            explanation; this is a wording-based check, not a hiring score.
          </p>
          <p className="mt-2 font-mono text-[11px] text-ink-faint">
            Required: {s.required.total} ({s.required.partial} partial,{" "}
            {s.required.verify} to verify, {s.required.gap} without evidence) ·
            Preferred: {s.preferred.total} · Priority unspecified:{" "}
            {s.unspecified.total}
          </p>
          {parsed.ignored ? (
            <p className="mt-1 text-[11px] text-ink-faint">
              Skipped {parsed.ignored} headings, duplicate lines or
              non-requirement lines. Review the extracted list.
            </p>
          ) : null}
          {parsed.truncated ? (
            <p className="mt-1 text-[12px] text-accent">
              Only the first 60 requirements within 20,000 characters were
              checked. Split the description to check the rest.
            </p>
          ) : null}
          <ol className="mt-3 divide-y divide-rule-faint border-y border-rule-faint">
            {rows.map((r, i) => (
              <li
                key={`${i}-${r.requirement}`}
                className="grid gap-x-4 gap-y-1.5 py-3 sm:grid-cols-[96px_1fr]"
              >
                <span
                  className={`self-start px-1.5 py-0.5 text-center font-mono text-[11px] tracking-wide uppercase ${BADGE[r.strength]}`}
                >
                  {STRENGTH_LABELS[r.strength]}
                </span>
                <div>
                  <p className="text-[14px] leading-snug text-ink">
                    {r.requirement}
                  </p>
                  <p className="mt-1 font-mono text-[10px] uppercase text-ink-faint">
                    {r.priority === "unspecified"
                      ? "Priority unspecified"
                      : r.priority}
                  </p>
                  <p className="mt-1 text-[12px] leading-relaxed text-ink-muted">
                    {r.explanation}
                  </p>
                  {r.evidence.length ? (
                    <p className="mt-1 flex flex-wrap gap-x-3 gap-y-0.5 font-mono text-[11px]">
                      {r.evidence.map((e) => (
                        <a
                          key={e.url + e.name}
                          href={e.url}
                          className="text-ink-muted underline decoration-rule underline-offset-2 hover:text-accent"
                        >
                          {e.name} · {e.scope} ↗
                        </a>
                      ))}
                    </p>
                  ) : (
                    <p className="mt-1 font-mono text-[11px] text-ink-faint">
                      No supporting link found.
                    </p>
                  )}
                </div>
              </li>
            ))}
          </ol>
          {questions.length ? (
            <div className="mt-6">
              <p className="font-mono text-[11px] tracking-[0.15em] text-ink-faint uppercase">
                Interview prep — explore the evidence
              </p>
              <ol className="mt-2 list-decimal space-y-1.5 pl-5 text-[14px] leading-snug text-ink-muted marker:font-mono marker:text-[11px] marker:text-accent">
                {questions.map((q) => (
                  <li key={q.q}>
                    {q.q}{" "}
                    <a
                      href={q.url}
                      className="font-mono text-[11px] text-ink-faint underline underline-offset-2 hover:text-accent"
                    >
                      read first ↗
                    </a>
                  </li>
                ))}
              </ol>
            </div>
          ) : null}
          <div className="mt-5 flex flex-wrap gap-3">
            <a
              href={stale ? undefined : replyHref(rows, ran)}
              aria-disabled={stale}
              onClick={() => {
                if (!stale) beacon("contact", { via: "fit" });
              }}
              className="border border-accent bg-accent px-3 py-1.5 font-mono text-[11px] text-paper hover:bg-transparent hover:text-accent"
            >
              email him about this role →
            </a>
            <button
              type="button"
              onClick={() => exportMd("copy")}
              disabled={stale}
              className="border border-rule px-3 py-1.5 font-mono text-[11px] text-ink-muted hover:border-accent hover:text-accent disabled:cursor-not-allowed disabled:opacity-40"
            >
              {copied ? "✓ brief copied" : "copy brief (markdown)"}
            </button>
            <button
              type="button"
              onClick={() => exportMd("download")}
              disabled={stale}
              className="border border-rule px-3 py-1.5 font-mono text-[11px] text-ink-muted hover:border-accent hover:text-accent disabled:cursor-not-allowed disabled:opacity-40"
            >
              download brief ↓
            </button>
          </div>
        </div>
      ) : ran ? (
        <p className="mt-4 text-sm text-ink-muted" role="status">
          No requirements extracted. Paste specific skills or qualifications,
          one per line.
        </p>
      ) : null}
    </div>
  );
}
